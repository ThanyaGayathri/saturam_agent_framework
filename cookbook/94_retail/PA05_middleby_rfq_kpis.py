def _call(api: str, method: str, path: str, body: Any = None) -> Any:
    data = json.dumps(body).encode() if body is not None else None
    request = urllib.request.Request(
        api + path,
        method=method,
        data=data,
        headers={"content-type": "application/json"},
    )
    with urllib.request.urlopen(request, timeout=300) as response:
        return json.loads(response.read().decode() or "null")


def register(api: str) -> List[str]:
    created: List[str] = []
    for kpi in RFQ_KPIS:
        body = {
            "identifier": kpi["identifier"],
            "name": kpi["name"],
            "description": kpi["description"],
            "business_area": "sales",
            "subject_area": "Sales Pipeline",
            "concept": kpi.get("concept", "Quote"),
            "grain": kpi["grain"],
            "result_shape": "scalar",
            "dialect": "postgres",
            "sql": kpi["sql"],
            "source_tables": kpi.get("source_tables", ["dc_rfq_quotes"]),
            "parameters": AS_OF,
            "time_window": kpi["time_window"],
            "level": "operational",
            "unit": kpi["unit"],
            "active": True,
        }
        try:
            _call(api, "POST", "/kpis", body)
            created.append(kpi["identifier"])
            print(f"  registered {kpi['identifier']}")
        except urllib.error.HTTPError as error:
            if error.code == 409:
                print(f"  already registered {kpi['identifier']}")
            else:
                print(
                    f"  REFUSED {kpi['identifier']}: {error.code} {error.read().decode()[:300]}"
                )
    return created


def compute(api: str) -> None:
    for kpi in RFQ_KPIS:
        identifier = kpi["identifier"]
        try:
            out = _call(api, "POST", f"/kpis/{identifier}/compute", {})
        except urllib.error.HTTPError as error:
            print(f"  FAILED {identifier}: {error.code} {error.read().decode()[:300]}")
            continue
        status = out.get("status") or out.get("verdict") or out
        rows = out.get("rows_written") or out.get("row_count") or out.get("rows")
        print(f"  computed {identifier:<36} {status} rows={rows}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--api", default="http://localhost:7777")
    parser.add_argument("--no-compute", action="store_true")
    parser.add_argument("--no-dashboard", action="store_true")
    args = parser.parse_args()
    print("Registering the RFQ KPI set")
    register(args.api)
    if not args.no_compute:
        print("Computing into gold as of today")
        compute(args.api)
    if not args.no_dashboard:
        print("Creating the dashboard under KPIs -> Dashboards")
        dashboard_id = create_dashboard(args.api)
        print(f"  open: http://localhost:3001/kpis/dashboards/{dashboard_id}")
    return 0


