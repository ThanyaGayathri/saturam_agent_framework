def create_dashboard(api: str) -> str:
    existing = _call(api, "GET", "/dashboards")
    rows = (
        existing.get("dashboards", existing) if isinstance(existing, dict) else existing
    )
    for row in rows:
        if row.get("name") == DASHBOARD_NAME:
            print(f"  dashboard already there: {row['id']}")
            return str(row["id"])
    body = {
        "name": DASHBOARD_NAME,
        "description": (
            "Full visibility into the quote pipeline -- from a quote being submitted through "
            "to closed-won or closed-lost -- by brand, PIM category, territory, state and "
            "customer segment, with the lost-reason breakdown and the live-chat intent signal."
        ),
        "tiles": [
            {
                "source": "kpi",
                "kpi_identifier": kpi,
                "title": title,
                "chart": chart,
                "position": {"x": x, "y": y, "w": w, "h": h},
            }
            for title, kpi, chart, x, y, w, h in TILES
        ],
        "refresh_schedule": "nightly",
        "visibility": "team",
    }
    created = _call(api, "POST", "/dashboards", body)
    print(
        f"  dashboard created: {created['id']} with {len(created.get('tiles', []))} tiles"
    )
    return str(created["id"])


