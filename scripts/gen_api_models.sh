#!/bin/bash

############################################################################
#
#    EGPT API contract -- regenerate everything derived from the source YAML.
#
#    The contract source is product/egpt_retail/api/openapi/egpt-retail.v1.yaml plus its
#    paths/ and schemas/ fragments. This script produces, in order:
#
#      1. the bundled document  (egpt-retail.v1.bundled.json)
#      2. the pydantic models   (egpt_retail/api/models/_generated.py)
#      3. the contract fixture  (egpt_retail/contracts/_fixtures/r3_contract.json)
#
#    All three are committed. ./scripts/validate.sh runs check_api_model_drift.py, which
#    rebuilds them into a temp dir and fails if the committed copies differ -- so the YAML
#    stays the source of truth in practice, not just in principle.
#
#    Usage: ./scripts/gen_api_models.sh
#
############################################################################

set -e

CURR_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(dirname "${CURR_DIR}")"
PRODUCT="${REPO_ROOT}/product/egpt_retail"

if ! command -v datamodel-codegen &> /dev/null && [[ -x "${REPO_ROOT}/.venv/bin/datamodel-codegen" ]]; then
    export PATH="${REPO_ROOT}/.venv/bin:${PATH}"
fi
if ! command -v datamodel-codegen &> /dev/null; then
    echo "    datamodel-codegen not found. Run ./scripts/dev_setup.sh first (it installs product[dev])."
    exit 1
fi

echo ""
echo "    EGPT API contract"
echo ""

echo "    bundling fragments -> egpt-retail.v1.bundled.json"
python3 -c "from egpt_retail.api.spec import write_bundle; print('      ', write_bundle())"

echo "    generating models  -> api/models/_generated.py"
datamodel-codegen \
  --input "${PRODUCT}/api/openapi/egpt-retail.v1.bundled.json" \
  --input-file-type openapi \
  --output "${PRODUCT}/api/models/_generated.py" \
  --output-model-type pydantic_v2.BaseModel \
  --target-python-version 3.10 \
  --use-standard-collections \
  --use-union-operator \
  --field-constraints \
  --use-schema-description \
  --collapse-root-models \
  --use-double-quotes \
  --disable-timestamp \
  --formatters black isort \
  --custom-file-header "# GENERATED by scripts/gen_api_models.sh from egpt-retail.v1.yaml. DO NOT EDIT. Edit the YAML and regenerate."

echo "    building fixture   -> contracts/_fixtures/r3_contract.json"
python3 -c "from egpt_retail.contracts.fixture_builder import write_contract_fixture; print('      ', write_contract_fixture())"

echo ""
echo "    Done. Commit all three outputs with the YAML change that produced them."
echo ""
