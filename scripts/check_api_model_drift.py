#!/usr/bin/env python3
"""Fail if anything derived from the API contract is stale.

Rebuilds the bundle, the generated models and the contract fixture into a temporary
directory and diffs each against the committed copy. The fix is always the same, and the
message says it: run ./scripts/gen_api_models.sh.

Do **not** replace this with "the stub's /openapi.json equals the source YAML". FastAPI
injects HTTPValidationError, reorders keys and normalises $refs, so that comparison is
permanently red. The committed artifacts are the gate.

Runs from ./scripts/validate.sh.
"""

from __future__ import annotations

import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from egpt_retail.api import spec
from egpt_retail.contracts import fixture_builder

REPO_ROOT = Path(__file__).resolve().parents[1]
MODELS = REPO_ROOT / "product" / "egpt_retail" / "api" / "models" / "_generated.py"
GEN_SCRIPT = REPO_ROOT / "scripts" / "gen_api_models.sh"

CODEGEN_ARGS = [
    "--input-file-type", "openapi",
    "--output-model-type", "pydantic_v2.BaseModel",
    "--target-python-version", "3.10",
    "--use-standard-collections",
    "--use-union-operator",
    "--field-constraints",
    "--use-schema-description",
    "--collapse-root-models",
    "--use-double-quotes",
    "--disable-timestamp",
    "--formatters", "black", "isort",
    "--custom-file-header",
    "# GENERATED by scripts/gen_api_models.sh from egpt-retail.v1.yaml. DO NOT EDIT. Edit the YAML and regenerate.",
]


def _codegen() -> str:
    """The generator installed beside this interpreter, so the check does not depend on PATH."""
    beside = Path(sys.executable).parent / "datamodel-codegen"
    if beside.exists():
        return str(beside)
    found = shutil.which("datamodel-codegen")
    if found:
        return found
    raise SystemExit("datamodel-codegen not found; run ./scripts/dev_setup.sh (it installs product[dev])")


def main() -> int:
    problems = []

    ok, why = spec.bundle_matches_committed()
    if not ok:
        problems.append(why)

    ok, why = fixture_builder.fixture_matches_committed()
    if not ok:
        problems.append(why)

    with tempfile.TemporaryDirectory() as tmp:
        bundle_path = Path(tmp) / "bundle.json"
        spec.write_bundle(bundle_path=bundle_path)
        fresh_models = Path(tmp) / "_generated.py"
        result = subprocess.run(
            [_codegen(), "--input", str(bundle_path), "--output", str(fresh_models), *CODEGEN_ARGS],
            capture_output=True,
            text=True,
        )
        if result.returncode != 0:
            problems.append(f"datamodel-codegen failed: {result.stderr.strip()[-400:]}")
        elif not MODELS.exists():
            problems.append(f"{MODELS} does not exist; run {GEN_SCRIPT.name}")
        elif fresh_models.read_text() != MODELS.read_text():
            problems.append(f"{MODELS} is stale; run ./scripts/{GEN_SCRIPT.name}")

    if problems:
        print("api contract drift:")
        for problem in problems:
            print("  -", problem)
        return 1
    print("api contract: bundle, models and fixture match the YAML source")
    return 0


if __name__ == "__main__":
    sys.exit(main())
