#!/usr/bin/env python3
"""The API contract, checked: a valid document, executable by the stub, and nothing stale.

Four checks, in the order a defect would be found:

1. **Valid OpenAPI**, via openapi-spec-validator.
2. **Every operation carries at least one response example** (204 excepted). The stub serves
   examples; an operation without one renders as a blank screen.
3. **Every example validates against its declared schema**, request bodies included, and
   **example names are unique within an operation**. The first is the guard against a silently
   mis-parsed flow mapping in the YAML -- a comma that became a bogus key fails here rather
   than at demo time. The second keeps the stub's ``?example=<name>`` unambiguous.
4. **Nothing derived from the YAML is stale**: the committed bundle, the generated models and
   the contract fixture are rebuilt into a temporary directory and compared byte for byte.
   The fix is always ``./scripts/gen_api_models.sh``, and the message says so.

Do **not** replace check 4 with "the stub's /openapi.json equals the source YAML". FastAPI
injects HTTPValidationError, reorders keys and normalises $refs, so that comparison is
permanently red. The committed artifacts are the gate.

Runs from ./scripts/validate.sh. Exits non-zero on any finding.
"""

from __future__ import annotations

import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any, Dict, List

import jsonschema
from openapi_spec_validator import validate

from egpt_retail.api import spec
from egpt_retail.contracts import fixture_builder

REPO_ROOT = Path(__file__).resolve().parents[1]
MODELS = REPO_ROOT / "product" / "egpt_retail" / "api" / "models" / "_generated.py"

#: Must match scripts/gen_api_models.sh exactly, or the drift check reports a phantom.
CODEGEN_ARGS = [
    "--input-file-type",
    "openapi",
    "--output-model-type",
    "pydantic_v2.BaseModel",
    "--target-python-version",
    "3.10",
    "--use-standard-collections",
    "--use-union-operator",
    "--field-constraints",
    "--use-schema-description",
    "--collapse-root-models",
    "--use-double-quotes",
    "--disable-timestamp",
    "--formatters",
    "black",
    "isort",
    "--custom-file-header",
    "# GENERATED by scripts/gen_api_models.sh from egpt-retail.v1.yaml. DO NOT EDIT. Edit the YAML and regenerate.",
]


def _iter_operations(document: Dict[str, Any]):
    for route, item in document["paths"].items():
        for method, operation in item.items():
            if method.startswith("x-") or method == "parameters":
                continue
            yield route, method.upper(), operation


def _validate_example(
    document: Dict[str, Any], schema: Dict[str, Any], value: Any, where: str
) -> List[str]:
    validator = jsonschema.Draft202012Validator(
        {**schema, "components": document["components"]}
    )
    return [
        f"{where}: {error.message[:160]} at /{'/'.join(str(p) for p in error.path)}"
        for error in list(validator.iter_errors(value))[:3]
    ]


def check_document(document: Dict[str, Any]) -> List[str]:
    """Checks 1 to 3."""
    validate(document)
    findings: List[str] = []
    for route, method, operation in _iter_operations(document):
        has_example = False
        seen: Dict[str, str] = {}
        body = (
            (operation.get("requestBody") or {})
            .get("content", {})
            .get("application/json")
        )
        if body and body.get("schema"):
            for name, example in (body.get("examples") or {}).items():
                findings += _validate_example(
                    document,
                    body["schema"],
                    example["value"],
                    f"{method} {route} request '{name}'",
                )
        for code, response in operation.get("responses", {}).items():
            media = (response.get("content") or {}).get("application/json")
            if not media:
                if code == "204":
                    has_example = True
                continue
            for name, example in (media.get("examples") or {}).items():
                has_example = True
                if name in seen:
                    findings.append(
                        f"{method} {route}: example name {name!r} is used on both {seen[name]} and {code}; "
                        "names must be unique per operation so ?example= is unambiguous"
                    )
                seen[name] = code
                if media.get("schema"):
                    findings += _validate_example(
                        document,
                        media["schema"],
                        example["value"],
                        f"{method} {route} {code} '{name}'",
                    )
        if not has_example:
            findings.append(
                f"{method} {route}: no response example; the stub would serve nothing"
            )
    return findings


def _codegen() -> str:
    """The generator installed beside this interpreter, so the check does not depend on PATH."""
    beside = Path(sys.executable).parent / "datamodel-codegen"
    if beside.exists():
        return str(beside)
    found = shutil.which("datamodel-codegen")
    if found:
        return found
    raise SystemExit(
        "datamodel-codegen not found; run ./scripts/dev_setup.sh (it installs product[dev])"
    )


def check_derived() -> List[str]:
    """Check 4."""
    problems: List[str] = []
    ok, why = spec.bundle_matches_committed()
    if not ok and why:
        problems.append(why)
    ok, why = fixture_builder.fixture_matches_committed()
    if not ok and why:
        problems.append(why)
    with tempfile.TemporaryDirectory() as tmp:
        bundle_path = Path(tmp) / "bundle.json"
        spec.write_bundle(bundle_path=bundle_path)
        fresh_models = Path(tmp) / "_generated.py"
        result = subprocess.run(
            [
                _codegen(),
                "--input",
                str(bundle_path),
                "--output",
                str(fresh_models),
                *CODEGEN_ARGS,
            ],
            capture_output=True,
            text=True,
        )
        if result.returncode != 0:
            problems.append(f"datamodel-codegen failed: {result.stderr.strip()[-400:]}")
        elif not MODELS.exists():
            problems.append(f"{MODELS} does not exist; run ./scripts/gen_api_models.sh")
        elif fresh_models.read_text() != MODELS.read_text():
            problems.append(f"{MODELS} is stale; run ./scripts/gen_api_models.sh")
    return problems


def main() -> int:
    document = spec.bundle()
    findings = check_document(document) + check_derived()
    operations = sum(1 for _ in _iter_operations(document))
    print(
        f"api contract: {operations} operations, {len(document['components']['schemas'])} schemas"
    )
    if findings:
        print(f"api contract: {len(findings)} finding(s)")
        for finding in findings:
            print("  -", finding)
        return 1
    print(
        "api contract: valid, every operation executable, generated artifacts match the source"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
