def patch_railway_deploy(target: Path) -> None:
    for script in ["up.sh", "redeploy.sh"]:
        script_path = target / "scripts" / "railway" / script
        if not script_path.is_file():
            continue
        text = script_path.read_text(encoding="utf-8")
        if 'railway up --service agent-os' in text:
            before = 'railway up --service agent-os'
            after = (
                'if [[ -z "${GITHUB_TOKEN:-}" ]]; then\n'
                '    echo "GITHUB_TOKEN is required to download the egpt wheels" >&2\n'
                '    exit 1\n'
                'fi\n'
                'railway variables --set "GITHUB_TOKEN=${GITHUB_TOKEN}" --service agent-os > /dev/null\n'
                'railway up --service agent-os'
            )
            text = text.replace(before, after)
            script_path.write_text(text, encoding="utf-8")
            warn(script + " now requires GITHUB_TOKEN at build time")


def rebrand_text(text: str, egpt_version: str, is_pyproject: bool) -> str:
    for pattern, replacement in PRE_RENAMES:
        text = pattern.sub(replacement, text)
    placeholders = {}
    for index, literal in enumerate(PROTECTED):
        token = "\x00P" + str(index) + "\x00"
        placeholders[token] = literal
        text = text.replace(literal, token)
    text = text.replace(UPSTREAM_BANNER, EGPT_BANNER)
    for pattern, replacement in RENAMES:
        text = pattern.sub(replacement, text)
    if is_pyproject:
        text = re.sub(r"(\"egpt\[[^\]]*\])==[0-9][0-9A-Za-z.!+]*", r"\1==" + egpt_version, text)
    for token, literal in placeholders.items():
        text = text.replace(token, literal)
    return text


def main() -> int:
    if len(sys.argv) != 4:
        print("Usage: rebrand_codemod.py <target_dir> <flavor> <egpt_version>", file=sys.stderr)
        return 2
    target = Path(sys.argv[1]).resolve()
    flavor = sys.argv[2]
    egpt_version = sys.argv[3]
    if flavor not in FLAVORS:
        print("Unknown flavor: " + flavor, file=sys.stderr)
        return 2
    if not target.is_dir():
        print("Not a directory: " + str(target), file=sys.stderr)
        return 2

    # Structural patches run first, against the upstream (pre-rename) text.
    if flavor == "railway":
        patch_dockerfile_railway(target)
    else:
        patch_dockerfile(target)
    patch_compose(target)
    patch_entrypoint(target)
    patch_venv_setup(target)
    patch_generate_requirements(target)
    patch_validate_workflow(target)
    patch_build_image(target)
    patch_mcp_json(target)
    patch_claude_settings(target)

    if flavor == "aws":
        patch_aws_deploy(target)
    elif flavor == "gcp":
        patch_gcp_deploy(target)
    elif flavor == "fly":
        patch_fly_deploy(target)
    elif flavor == "railway":
        patch_railway_deploy(target)

    changed = 0
    for path in sorted(target.rglob("*")):
        if ".git" in path.parts or path.name in SKIP_FILES:
            continue
        if not is_text_file(path):
            continue
        original = path.read_text(encoding="utf-8")
        rebranded = rebrand_text(original, egpt_version, is_pyproject=path.name == "pyproject.toml")
        if rebranded != original:
            path.write_text(rebranded, encoding="utf-8")
            changed += 1

    print("")
    print("Rebranded " + str(changed) + " files in " + str(target))
    if warnings:
        print(str(len(warnings)) + " warning(s) above need manual attention.")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
