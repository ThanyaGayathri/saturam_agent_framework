#!/usr/bin/env python3
"""Rebrand an upstream agentos-* starter template checkout in place.

Applies the EGPT-0.4-0.7 naming conventions (agno -> egpt, AgentOS -> EgptOS,
AGNO_* -> EGPT_*) to a cloned agno-agi/agentos-<flavor> tree, plus structural
patches so the template installs the egpt framework from GitHub release wheels
instead of resolving agno from PyPI.

Invoked by rebrand_template.sh; not meant to be run twice on the same tree.

Usage: rebrand_codemod.py <target_dir> <flavor> <egpt_version>
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

FLAVORS = ("docker", "aws", "fly", "gcp", "railway")

# Files never touched by the codemod. requirements.txt is regenerated by
# scripts/generate_requirements.sh instead of being rewritten mechanically.
SKIP_FILES = {"requirements.txt", "LICENSE", "NOTICE"}

# Strings that must survive the mechanical agno/agentos renames.
#   - openinference-instrumentation-agno is a real third-party PyPI package.
#   - AGENTOS_URL / AGENTOS_MCP_SIGNING_KEY are still the env names the
#     framework and egptctl read (egptctl/discovery.py hardcodes AGENTOS_URL).
#   - The agno.com domains are left intact on purpose: they must be removed by
#     the manual editing pass, and the `check` grep flags any that remain.
PROTECTED = [
    "openinference-instrumentation-agno",
    "AGENTOS_URL",
    "AGENTOS_MCP_SIGNING_KEY",
    "os.agno.com",
    "docs.agno.com",
    "agno.link",
    "agno.com",
]

